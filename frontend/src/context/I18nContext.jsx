const I18nContext = createContext(null);

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(() => localStorage.getItem('lang') || 'fr');

  function setLang(l) {
    setLangState(l);
    localStorage.setItem('lang', l);
  }

  /** t('section.key') or t('section.key', { var: val }) for {var} interpolation */
  function t(key, vars = {}) {
    const keys = key.split('.');
    let val = T[lang];
    for (const k of keys) {
      val = val?.[k];
      if (val === undefined) return key;
    }
    if (typeof val === 'string' && Object.keys(vars).length) {
      return val.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : `{${k}}`));
    }
    return val;
  }

  return (
    <I18nContext.Provider value={{ lang, setLang, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}
